"""Track B: depth-aware responsibility allocation. SEPARATE from v2's frozen conditions.py
(the 2,250 v2 runs are never affected).

At depth D both conditions run exactly D agents / D-1 handoffs. The ONLY difference:
  generalist                 : every agent holds ALL D responsibility blocks (concentrated).
  specialized_length_matched : agent i holds ONLY block i, plus frozen inert padding sized so its
                               per-agent system-prompt token budget matches the generalist's
                               (distributed). Padding is generated by data/build_padding_trackB.py.

So any widening A-vs-C gap as D grows is attributable to responsibility CONCENTRATION vs DISTRIBUTION,
not to agent count, handoffs, instruction content, or prompt length (all matched).
"""
from __future__ import annotations
import os
from agent import Agent
from llm import OllamaClient

_PROMPT_DIR = os.path.join(os.path.dirname(__file__), "..", "config", "prompts")

# ordered role -> block file, per depth level
DEPTH_ROLES = {
    3: ["retrieve", "solve", "verify"],
    5: ["retrieve", "extract", "plan", "solve", "verify"],
    7: ["retrieve", "extract", "plan", "solveA", "solveB", "aggregate", "verify"],
}
_BLOCK_FILE = {
    "retrieve": "block_retrieve.txt", "extract": "block_extract.txt", "plan": "block_plan.txt",
    "solve": "block_solve.txt", "solveA": "block_solveA.txt", "solveB": "block_solveB.txt",
    "aggregate": "block_aggregate.txt", "verify": "block_verify.txt",
}


def _read(name: str) -> str:
    with open(os.path.join(_PROMPT_DIR, name), "r", encoding="utf-8") as f:
        return f.read().strip()


def _pad_file(depth: int, role: str, model_tag: str | None = None) -> str:
    # model_tag=None -> original Qwen padding (pad_trackB_D{d}_{role}.txt, already frozen);
    # otherwise per-model padding sized with that model's own tokenizer.
    tag = f"{model_tag}_" if model_tag else ""
    return f"pad_trackB_{tag}D{depth}_{role}.txt"


def build_system_prompt(preamble: str, blocks: list[str]) -> str:
    return preamble + "\n\n" + "\n\n".join(blocks)


def build_agents_trackB(condition: str, depth: int, client: OllamaClient, max_tool_iters: int,
                        allow_missing_pad: bool = False, model_tag: str | None = None) -> list[Agent]:
    if depth not in DEPTH_ROLES:
        raise ValueError(f"unsupported depth {depth}; choose from {sorted(DEPTH_ROLES)}")
    preamble = _read("preamble.txt")
    roles = DEPTH_ROLES[depth]
    all_blocks = [_read(_BLOCK_FILE[r]) for r in roles]

    agents = []
    for i, role in enumerate(roles):
        if condition == "generalist":
            blocks = list(all_blocks)                       # every agent holds ALL blocks
        elif condition == "specialized_length_matched":
            own = _read(_BLOCK_FILE[role])
            pad_path = os.path.join(_PROMPT_DIR, _pad_file(depth, role, model_tag))
            if os.path.exists(pad_path):
                blocks = [own, _read(_pad_file(depth, role, model_tag))]
            elif allow_missing_pad:
                blocks = [own]                              # offline structure test only
            else:
                raise FileNotFoundError(
                    f"missing padding {pad_path}. Run: python data/build_padding_trackB.py "
                    f"(needs Ollama) to freeze length-matched padding before the confirmatory run.")
        else:
            raise ValueError(f"unknown condition: {condition}")
        sp = build_system_prompt(preamble, blocks)
        agents.append(Agent(i, role, sp, client, max_tool_iters))
    return agents
